RANKS = "23456789TJQKA"
SUITS = "shdc"
CI = {r + s: i * 4 + j for i, r in enumerate(RANKS) for j, s in enumerate(SUITS)}
CS = {v: k for k, v in CI.items()}

# ---- straight / flush lookup tables over 13-bit rank masks
STR_HIGH = [-1] * 8192
for _m in range(8192):
    _b = -1
    for _hi in range(12, 3, -1):
        _w = 31 << (_hi - 4)
        if _m & _w == _w:
            _b = _hi
            break
    if _b < 0 and (_m & 0x100F) == 0x100F:
        _b = 3
    STR_HIGH[_m] = _b

TOP5 = {}
for _m in range(8192):
    if _m.bit_count() >= 5:
        _k = 0
        _n = 0
        for _r in range(12, -1, -1):
            if _m >> _r & 1:
                _k = _k * 13 + _r
                _n += 1
                if _n == 5:
                    break
        TOP5[_m] = _k

NDIG = (5, 4, 3, 3, 1, 5, 2, 2, 1)  # digits per category (for normalising)
NORM = tuple(13 ** d for d in NDIG)


def ev(cards):
    """Strength int of the best 5-card hand among 5..7 cards (higher = better)."""
    s0 = s1 = s2 = s3 = 0
    rc = [0] * 13
    for c in cards:
        r = c >> 2
        b = 1 << r
        s = c & 3
        if s == 0:
            s0 |= b
        elif s == 1:
            s1 |= b
        elif s == 2:
            s2 |= b
        else:
            s3 |= b
        rc[r] += 1
    fm = 0
    if s0.bit_count() >= 5:
        fm = s0
    elif s1.bit_count() >= 5:
        fm = s1
    elif s2.bit_count() >= 5:
        fm = s2
    elif s3.bit_count() >= 5:
        fm = s3
    if fm:
        h = STR_HIGH[fm]
        if h >= 0:
            return (8 << 24) | h
        return (5 << 24) | TOP5[fm]
    quad = -1
    trips = []
    pairs = []
    singles = []
    for r in range(12, -1, -1):
        n = rc[r]
        if n == 0:
            continue
        if n == 4:
            quad = r
        elif n == 3:
            trips.append(r)
        elif n == 2:
            pairs.append(r)
        else:
            singles.append(r)
    if quad >= 0:
        k = -1
        for r in range(12, -1, -1):
            if rc[r] and r != quad:
                k = r
                break
        return (7 << 24) | (quad * 13 + k)
    if trips and (len(trips) > 1 or pairs):
        t = trips[0]
        p = max(trips[1:] + pairs)
        return (6 << 24) | (t * 13 + p)
    allm = s0 | s1 | s2 | s3
    sh = STR_HIGH[allm]
    if sh >= 0:
        return (4 << 24) | sh
    if trips:
        t = trips[0]
        oth = sorted(pairs + singles, reverse=True)[:2]
        return (3 << 24) | ((t * 13 + oth[0]) * 13 + oth[1])
    if len(pairs) >= 2:
        p1, p2 = pairs[0], pairs[1]
        rest = pairs[2:] + singles
        k = max(rest) if rest else 0
        return (2 << 24) | ((p1 * 13 + p2) * 13 + k)
    if pairs:
        p = pairs[0]
        k1, k2, k3 = singles[0], singles[1], singles[2]
        return (1 << 24) | (((p * 13 + k1) * 13 + k2) * 13 + k3)
    k = 0
    for r in singles[:5]:
        k = k * 13 + r
    return k  # category 0


def keep_s(keep2, flop3):
    """Heuristic strength of keeping `keep2` on a 3-card flop: made hand + draw bonuses."""
    cards = [keep2[0], keep2[1], flop3[0], flop3[1], flop3[2]]
    v = ev(cards)
    cat = v >> 24
    s = cat + 0.8 * ((v & 0xFFFFFF) / NORM[cat])
    if cat < 5:
        sc = [0, 0, 0, 0]
        for c in cards:
            sc[c & 3] += 1
        if sc[0] >= 4 or sc[1] >= 4 or sc[2] >= 4 or sc[3] >= 4:
            s += 0.35
    if cat < 4:
        m = 0
        for c in cards:
            m |= 1 << (c >> 2)
        if m & 4096:
            m |= 8192  # ace also low
        for lo in range(0, 10):
            if (m >> lo & 31).bit_count() >= 4:
                s += 0.25
                break
    return s


def best_keep_index(hole3, flop3):
    """Index i (discard hole3[i]) maximising keep_s; ties -> higher ranks kept."""
    best = None
    bi = 0
    for i in range(3):
        k = [hole3[a] for a in range(3) if a != i]
        key = (keep_s(k, flop3), (k[0] >> 2) + (k[1] >> 2))
        if best is None or key > best:
            best = key
            bi = i
    return bi


# ---- preflop canonical key (suit isomorphism)
PERMS = list(permutations(range(4)))


def canon3(hole3):
    best = None
    for p in PERMS:
        t = tuple(sorted(((c >> 2) * 4 + p[c & 3] for c in hole3), reverse=True))
        if best is None or t < best:
            best = t
    return best


def logit(p):
    p = min(0.995, max(0.005, p))
    return math.log(p / (1 - p))


def sigm(x):
    if x > 30:
        return 1.0
    if x < -30:
        return 0.0
    return 1.0 / (1.0 + math.exp(-x))

