# ----------------------------------------------------------------- preflop model
class PreflopModel:
    def __init__(self, table):
        self.table = table
        items = sorted(((e, c) for (e, c) in table.values()), reverse=True)
        self.e = [e for e, c in items]
        self.cum = []
        tot = 0
        for e, c in items:
            tot += c
            self.cum.append(tot)
        self.total = tot
        s = sum(e * c for e, c in items)
        self.avg_all = s / tot if tot else 0.5
        self._ecum = []
        acc = 0.0
        for e, c in items:
            acc += e * c
            self._ecum.append(acc)
        self.cache = {}

    def e0(self, hole3):
        k = canon3(hole3)
        v = self.table.get(k)
        return v[0] if v else 0.5

    def avg_top(self, q):
        """mean e0 of the best q fraction (by combos) of starting hands"""
        q = clamp(q, 0.01, 1.0)
        target = q * self.total
        i = bisect_left(self.cum, target)
        if i >= len(self.cum):
            i = len(self.cum) - 1
        prev_c = self.cum[i - 1] if i > 0 else 0
        prev_e = self._ecum[i - 1] if i > 0 else 0.0
        part = target - prev_c
        return (prev_e + part * self.e[i]) / target

    def vs_top(self, e0, q):
        """BT-model equity of a hand with uniform-equity e0 against the top q range"""
        return sigm(logit(e0) - logit(self.avg_top(q)) + logit(self.avg_all))

    def pct(self, e0):
        """fraction of starting hands strictly better than e0 (0 = best)"""
        k = bisect_left([-x for x in self.e], -e0)
        return self.cum[k - 1] / self.total if k > 0 else 0.0


