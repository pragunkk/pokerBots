#!/usr/bin/env python3
"""Regenerate the 1,755-class preflop table with many more samples (offline, runs on your laptop).

    python tools/gen_preflop.py --samples 20000 --workers 8

What it measures: equity of a 3-card hand against a random 3-card hand when BOTH players
keep the 2 cards that look best on the flop (same model the bot uses), then run out.
At 20,000 samples per class the noise is about +/-0.35 points (the current table is about +/-4).

Output: Starter_Kit/preflop_table.py (old file saved as preflop_table_old.py) and
tools/preflop_raw.json with the raw equities.

By default the new equities are QUANTILE-MAPPED onto the old table's values: the hand order
comes from the new, accurate simulation, but the same share of hands sits above each threshold
(0.32, 0.43, 0.57 ...), so every threshold in adaptive_bot.py keeps its meaning.
Use --raw to write raw equities instead (then you must re-tune the thresholds)."""
import argparse, json, os, random, shutil, sys, time
from itertools import combinations
from multiprocessing import Pool

KIT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Starter_Kit")
sys.path.insert(0, KIT)
import fast_eval as fe  # noqa: E402

E5, E7, RK, ST = fe.eval5_idx, fe.eval7_idx, fe.CARD_RANK, fe.CARD_SUIT
PAIR_OF_KINGS = (1 << 20) | (13 << 12)

def flop_keep(c3, b):
    """Index pair of the 2 cards that look best on the flop (made hand, 4-flush counts as a pair of kings)."""
    best, keep = -1, None
    for k0, k1 in ((c3[0], c3[1]), (c3[0], c3[2]), (c3[1], c3[2])):
        s = E5(k0, k1, b[0], b[1], b[2])
        if ST[k0] == ST[k1] and sum(ST[x] == ST[k0] for x in b) == 2:
            s = max(s, PAIR_OF_KINGS)
        if s > best:
            best, keep = s, (k0, k1)
    return keep

def equity(args):
    key, rep, n, seed = args
    rng = random.Random(seed)
    rest = [i for i in range(52) if i not in rep]
    won = 0.0
    for _ in range(n):
        s = rng.sample(rest, 8)
        opp, board = s[:3], s[3:]
        mk, ok = flop_keep(rep, board), flop_keep(opp, board)
        me = E7((mk[0], mk[1], *board)); op = E7((ok[0], ok[1], *board))
        won += 1.0 if me > op else 0.5 if me == op else 0.0
    return key, won / n

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--samples", type=int, default=20000)
    ap.add_argument("--workers", type=int, default=os.cpu_count() or 2)
    ap.add_argument("--raw", action="store_true")
    ap.add_argument("--limit", type=int, default=0, help="only the first N classes (for a quick test)")
    a = ap.parse_args()

    classes = {}
    for combo in combinations(fe.ALL_CARDS, 3):
        k = fe.canonical_3card_key(list(combo))
        classes.setdefault(k, [fe.CARD_IDX[c] for c in combo])
    keys = sorted(classes)
    assert len(keys) == 1755, len(keys)
    if a.limit:
        keys = keys[:a.limit]
    jobs = [(k, classes[k], a.samples, hash(k) & 0xFFFFFFFF) for k in keys]
    t0 = time.time()
    raw = {}
    with Pool(a.workers) as pool:
        for i, (k, e) in enumerate(pool.imap_unordered(equity, jobs, chunksize=4), 1):
            raw[k] = e
            if i % 100 == 0 or i == len(jobs):
                el = time.time() - t0
                print(f"  {i}/{len(jobs)} classes  {el:.0f}s elapsed, ~{el / i * (len(jobs) - i):.0f}s left", flush=True)

    with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "preflop_raw.json"), "w") as f:
        json.dump({str(k): v for k, v in raw.items()}, f)
    if a.limit:
        for k in keys:
            print(k, f"new {raw[k]:.4f}   old {fe.PREFLOP_TABLE_1755[k]:.4f}")
        return

    if a.raw:
        table = raw
    else:  # quantile-map onto the old distribution so thresholds keep their meaning
        old_sorted = sorted(fe.PREFLOP_TABLE_1755.values())
        new_order = sorted(raw, key=lambda k: raw[k])
        table = {k: old_sorted[i] for i, k in enumerate(new_order)}

    dest = os.path.join(KIT, "preflop_table.py")
    shutil.copy(dest, os.path.join(KIT, "preflop_table_old.py"))
    with open(dest, "w") as f:
        f.write('"""Precomputed 1,755 canonical 3-card preflop table for Discard Hold\'em.\n'
                f'Generated by tools/gen_preflop.py with {a.samples} samples per class'
                f'{" (raw equity)" if a.raw else " (quantile-mapped onto the previous scale)"}."""\n\n')
        f.write("PREFLOP_TABLE_1755 = {\n")
        for k in sorted(table, reverse=True):
            f.write(f"    {k}: {table[k]:.4f},\n")
        f.write("}\n")
    print(f"wrote {dest}  ({time.time() - t0:.0f}s)")

if __name__ == "__main__":
    main()
