#!/usr/bin/env python3
"""
Bundles `Starter_Kit/preflop_table.py` + `Starter_Kit/fast_eval.py` + `rl_bot/core_rl_bot.py`
into a single self-contained tournament submission file: `rl_bot/bot.py` (with all neural & RL
weights embedded directly in the file, zero external dependencies).
"""

import ast
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
KIT = ROOT / "Starter_Kit"
RL_DIR = ROOT / "rl_bot"

SOURCES = [
    KIT / "preflop_table.py",
    KIT / "fast_eval.py",
    RL_DIR / "core_rl_bot.py",
]
OUT = RL_DIR / "bot.py"

INTERNAL_MODULES = {"preflop_table", "fast_eval", "core_rl_bot"}

HEADER = '''#!/usr/bin/env python3
"""
Standalone tournament submission — NeuralCFRBot (Deep Counterfactual Regret + Contextual Meta-RL Bot).
Generated by rl_bot/build_rl_bot.py from Starter_Kit/preflop_table.py, Starter_Kit/fast_eval.py,
and rl_bot/core_rl_bot.py. All pre-trained neural network weights and RL policy parameters are
embedded directly inside this file (Python 3.11 standard library only).
"""
'''


def strip_internal_imports(src: str) -> str:
    pattern = re.compile(
        r"^from\s+(" + "|".join(INTERNAL_MODULES) + r")\s+import\s+"
        r"(?:\([^)]*\)|[^\n]*)\n",
        re.MULTILINE,
    )
    return pattern.sub("", src)


def build():
    parts = [HEADER]
    for path in SOURCES:
        text = strip_internal_imports(path.read_text())
        parts.append(f"\n# {'=' * 75}\n# {path.name}\n# {'=' * 75}\n\n{text.strip()}\n")
    bundle = "".join(parts)
    ast.parse(bundle)
    OUT.write_text(bundle)
    size_kb = OUT.stat().st_size / 1024
    assert size_kb < 5000, f"rl_bot/bot.py too big: {size_kb:.1f} KB"
    print(f"Wrote standalone RL submission {OUT.relative_to(ROOT)}  ({size_kb:.1f} KB, 0 external deps)")


if __name__ == "__main__":
    build()
